  const DICTS = { en, de };
  let lang = 'en';
  try {
    const saved = JSON.parse(localStorage.getItem('otd.lang'));
    lang = saved || ((navigator.language || '').toLowerCase().startsWith('de') ? 'de' : 'en');
  } catch (e) { /* ignore */ }
  if (!DICTS[lang]) lang = 'en';

  function t(key, vars) {
    let s = DICTS[lang][key];
    if (s == null) s = en[key];
    if (s == null) return key;
    if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return s;
  }

  // German override for a survivor text, or null to fall back to the English data
  function tx(key) {
    return lang === 'en' ? null : (DICTS[lang][key] != null ? DICTS[lang][key] : null);
  }

  function applyI18n(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.documentElement.lang = lang;
  }

  const listeners = [];
  function setLang(l) {
    if (!DICTS[l] || l === lang) return;
    lang = l;
    try { localStorage.setItem('otd.lang', JSON.stringify(l)); } catch (e) { /* ignore */ }
    applyI18n();
    for (const fn of listeners) fn(l);
  }

